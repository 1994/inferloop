use super::{
    block::BlockScanner,
    types::{
        MAX_TOOL_ARGUMENT_BYTES, MAX_TOOL_CALLS, ParsedOutput, ParsedToolCall, REASONING_CLOSE,
        REASONING_OPEN, StreamEvent, TOOL_CALL_CLOSE, TOOL_CALL_OPEN, ToolDialect,
    },
};
use std::collections::BTreeMap;
use std::collections::BTreeSet;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ToolRecognition {
    Enabled,
    Disabled,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Emission {
    Complete,
    Arguments,
}
/// Parser phase for one streamed response.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Phase {
    /// Nothing published yet; deciding between a reasoning block and plain text.
    Start,
    Reasoning,
    Text,
    Call,
    Done,
}

/// Incremental parser for one model response.
///
/// `feed` consumes only newly committed text and never revisits it, so parsing a response costs
/// one pass over its length. Text is published lazily: a trailing whitespace run and a suffix
/// that could still become a marker are held back. That is what makes the concatenated deltas
/// equal the non-streaming result exactly, rather than approximately, and it is why
/// [`parse_with`] is defined as this parser fed the whole response.
#[derive(Debug, Clone)]
pub struct OutputStreamParser {
    dialect: ToolDialect,
    declared: Option<BTreeSet<String>>,
    phase: Phase,
    /// Received text not yet published, consumed or held back.
    buffer: String,
    /// Bytes at the start of `buffer` already known not to open the closing marker.
    scanner: BlockScanner,
    emission: Emission,
    tools: ToolRecognition,
    announced: Option<String>,
    argument_bytes: usize,
    text_scan: usize,
    whitespace_start: usize,
    /// Calls published so far, bounded by `MAX_TOOL_CALLS`.
    calls: usize,
    truncated: bool,
    text_published: bool,
    reasoning_published: bool,
}

impl OutputStreamParser {
    /// Create a parser for one response.
    #[must_use]
    pub const fn new(dialect: ToolDialect, declared: Option<BTreeSet<String>>) -> Self {
        Self {
            dialect,
            declared,
            phase: Phase::Start,
            buffer: String::new(),
            scanner: BlockScanner::new(dialect),
            emission: Emission::Complete,
            tools: ToolRecognition::Enabled,
            announced: None,
            argument_bytes: 0,
            text_scan: 0,
            whitespace_start: 0,
            calls: 0,
            truncated: false,
            text_published: false,
            reasoning_published: false,
        }
    }
    /// Control tool-region recognition independently of reasoning parsing.
    #[must_use]
    pub const fn with_tools(mut self, enabled: bool) -> Self {
        self.tools = if enabled {
            ToolRecognition::Enabled
        } else {
            ToolRecognition::Disabled
        };
        self
    }
    /// Enable append-only tool argument events. Invalid output after publication is an error.
    #[must_use]
    pub const fn with_argument_deltas(mut self) -> Self {
        self.emission = Emission::Arguments;
        self
    }
    /// Whether the rendered generation prefix has already opened a reasoning region.
    #[must_use]
    pub fn prompt_opens_reasoning(prompt: &str) -> bool {
        prompt.trim_end().ends_with(REASONING_OPEN)
    }
    /// Start inside a reasoning region opened by the prompt, before feeding generated text.
    #[must_use]
    pub const fn with_open_reasoning(mut self, enabled: bool) -> Self {
        if enabled {
            self.phase = Phase::Reasoning;
        }
        self
    }
    fn consume(&mut self, bytes: usize) {
        self.buffer.drain(..bytes);
        self.text_scan = self.text_scan.saturating_sub(bytes);
        self.whitespace_start = self.whitespace_start.saturating_sub(bytes);
    }
    fn clear(&mut self) {
        self.buffer.clear();
        self.text_scan = 0;
        self.whitespace_start = 0;
    }
    /// Feed newly committed text and take whatever is now stable.
    ///
    /// # Errors
    /// Returns an invalid-input error when a tool-call body exceeds `MAX_TOOL_ARGUMENT_BYTES` or
    /// the response publishes more than `MAX_TOOL_CALLS` calls. Returns a backend error when
    /// generated bytes invalidate a call whose argument prefix has already been published.
    pub fn feed(&mut self, chunk: &str) -> infer_core::Result<Vec<StreamEvent>> {
        let nonspace = chunk.trim_end().len();
        if nonspace > 0 {
            self.whitespace_start = self.buffer.len() + nonspace;
        }
        self.buffer.push_str(chunk);
        self.drain(false)
    }
    /// Finish the response, publishing the remaining stable text and dropping held whitespace.
    ///
    /// # Errors
    /// Returns the same invalid-input errors as [`Self::feed`].
    pub fn finish(&mut self) -> infer_core::Result<Vec<StreamEvent>> {
        self.drain(true)
    }
    /// True when a tool call opened without closing, so its tail was withheld.
    #[must_use]
    pub const fn truncated(&self) -> bool {
        self.truncated
    }
    fn drain(&mut self, flush: bool) -> infer_core::Result<Vec<StreamEvent>> {
        let mut events = Vec::new();
        loop {
            let progressed = match self.phase {
                Phase::Done => break,
                Phase::Start => self.drain_start(flush),
                Phase::Reasoning => self.drain_reasoning(flush, &mut events),
                Phase::Text => self.drain_text(flush, &mut events),
                Phase::Call => self.drain_call(flush, &mut events)?,
            };
            if !progressed {
                break;
            }
        }
        Ok(events)
    }
    /// Decide between a reasoning block and plain text. Returns whether to keep draining.
    fn drain_start(&mut self, flush: bool) -> bool {
        // Hold while the buffer could still become the reasoning marker.
        if !flush && REASONING_OPEN.starts_with(self.buffer.as_str()) {
            return false;
        }
        if self.buffer.starts_with(REASONING_OPEN) {
            self.consume(REASONING_OPEN.len());
            self.text_scan = 0;
            self.phase = Phase::Reasoning;
        } else {
            self.phase = Phase::Text;
        }
        true
    }
    fn drain_reasoning(&mut self, flush: bool, events: &mut Vec<StreamEvent>) -> bool {
        let Some(index) = self.buffer[self.text_scan..]
            .find(REASONING_CLOSE)
            .map(|i| i + self.text_scan)
        else {
            self.text_scan = floor_boundary(
                &self.buffer,
                self.buffer.len().saturating_sub(REASONING_CLOSE.len() - 1),
            );
            let hold = if flush {
                self.buffer.len() - self.whitespace_start
            } else {
                hold_len(&self.buffer, REASONING_CLOSE, self.whitespace_start)
            };
            let end = self.buffer.len() - hold;
            let ready = self.buffer[..end].to_string();
            self.consume(end);
            self.publish_reasoning(&ready, events);
            if flush {
                // A reasoning block that never closed leaves no assistant text, but all of it was
                // published: the model finished thinking aloud, which is not a malformed answer.
                self.clear();
                self.phase = Phase::Done;
            }
            return false;
        };
        let head = self.buffer[..index].trim_end().to_string();
        self.consume(index + REASONING_CLOSE.len());
        self.text_scan = 0;
        self.publish_reasoning(&head, events);
        self.phase = Phase::Text;
        true
    }
    fn drain_text(&mut self, flush: bool, events: &mut Vec<StreamEvent>) -> bool {
        if let Some(index) = (self.tools == ToolRecognition::Enabled)
            .then(|| {
                self.buffer[self.text_scan..]
                    .find(TOOL_CALL_OPEN)
                    .map(|i| i + self.text_scan)
            })
            .flatten()
        {
            let head = self.buffer[..index].trim_end().to_string();
            self.consume(index + TOOL_CALL_OPEN.len());
            self.publish_text(&head, events);
            self.text_scan = 0;
            self.scanner = BlockScanner::new(self.dialect);
            self.announced = None;
            self.argument_bytes = 0;
            self.phase = Phase::Call;
            return true;
        }
        self.text_scan = floor_boundary(
            &self.buffer,
            self.buffer.len().saturating_sub(TOOL_CALL_OPEN.len() - 1),
        );
        let hold = if flush {
            self.buffer.len() - self.whitespace_start
        } else {
            hold_len(&self.buffer, TOOL_CALL_OPEN, self.whitespace_start)
        };
        let end = self.buffer.len() - hold;
        let ready = self.buffer[..end].to_string();
        self.consume(end);
        self.publish_text(&ready, events);
        if flush {
            self.clear();
            self.phase = Phase::Done;
        }
        false
    }
    fn drain_call(
        &mut self,
        flush: bool,
        events: &mut Vec<StreamEvent>,
    ) -> infer_core::Result<bool> {
        let end = self.scanner.scan(&self.buffer, flush);
        let body_end = end.unwrap_or(self.buffer.len());
        if body_end
            > MAX_TOOL_ARGUMENT_BYTES
                + if end.is_none() {
                    TOOL_CALL_CLOSE.len() - 1
                } else {
                    0
                }
        {
            return Err(infer_core::Error::invalid(
                "tool call exceeds its byte budget",
            ));
        }
        if self.emission == Emission::Arguments {
            self.publish_arguments(events)?;
        }
        let Some(end) = end else {
            if flush {
                self.truncated = true;
                self.clear();
                self.phase = Phase::Done;
            }
            return Ok(false);
        };
        let call = self.scanner.complete(&self.buffer[..end]);
        let allowed = call.as_ref().is_some_and(|call| {
            self.allowed(&call.name)
                && call.arguments.len() <= MAX_TOOL_ARGUMENT_BYTES
                && self
                    .announced
                    .as_ref()
                    .is_none_or(|name| name == &call.name)
                && (self.announced.is_none()
                    || self.scanner.arguments(&self.buffer) == Some(call.arguments.as_str()))
        });
        if allowed {
            if self.calls >= MAX_TOOL_CALLS {
                return Err(infer_core::Error::invalid("too many tool calls"));
            }
            if self.announced.is_some() {
                events.push(StreamEvent::CallEnd { index: self.calls });
            } else if let Some(call) = call {
                events.push(StreamEvent::Call(call));
            }
            self.calls += 1;
        } else if self.announced.is_some() {
            return Err(infer_core::Error::new(
                infer_core::ErrorCode::Backend,
                "generated tool call is invalid after argument publication",
            ));
        } else {
            events.push(StreamEvent::Text(format!(
                "{TOOL_CALL_OPEN}{}{TOOL_CALL_CLOSE}",
                &self.buffer[..end]
            )));
            self.text_published = true;
        }
        self.consume(end + TOOL_CALL_CLOSE.len());
        self.text_scan = 0;
        self.phase = Phase::Text;
        Ok(true)
    }
    fn allowed(&self, name: &str) -> bool {
        self.declared
            .as_ref()
            .is_none_or(|names| names.contains(name))
    }
    fn publish_arguments(&mut self, events: &mut Vec<StreamEvent>) -> infer_core::Result<()> {
        let Some(name) = self.scanner.name() else {
            return Ok(());
        };
        if !self.allowed(name) {
            return Ok(());
        }
        let Some(arguments) = self.scanner.arguments(&self.buffer) else {
            return Ok(());
        };
        if arguments.len() > MAX_TOOL_ARGUMENT_BYTES {
            return Err(infer_core::Error::invalid(
                "tool arguments exceed their byte budget",
            ));
        }
        if let Some(previous) = self.announced.as_ref() {
            if previous != name {
                return Err(infer_core::Error::new(
                    infer_core::ErrorCode::Backend,
                    "generated tool name changed after publication",
                ));
            }
        } else {
            if self.calls >= MAX_TOOL_CALLS {
                return Err(infer_core::Error::invalid("too many tool calls"));
            }
            self.announced = Some(name.to_string());
            events.push(StreamEvent::CallStart {
                index: self.calls,
                name: name.to_string(),
            });
        }
        if arguments.len() > self.argument_bytes {
            events.push(StreamEvent::CallArguments {
                index: self.calls,
                arguments: arguments[self.argument_bytes..].to_string(),
            });
            self.argument_bytes = arguments.len();
        }
        Ok(())
    }
    fn publish_text(&mut self, chunk: &str, events: &mut Vec<StreamEvent>) {
        let text = if self.text_published {
            chunk
        } else {
            chunk.trim_start()
        };
        if text.is_empty() {
            return;
        }
        self.text_published = true;
        events.push(StreamEvent::Text(text.to_string()));
    }
    fn publish_reasoning(&mut self, chunk: &str, events: &mut Vec<StreamEvent>) {
        let text = if self.reasoning_published {
            chunk
        } else {
            chunk.trim_start()
        };
        if text.is_empty() {
            return;
        }
        self.reasoning_published = true;
        events.push(StreamEvent::Reasoning(text.to_string()));
    }
}

/// Assemble published events into the non-streaming result.
#[must_use]
pub fn assemble(events: Vec<StreamEvent>, truncated: bool) -> ParsedOutput {
    let mut content = String::new();
    let mut reasoning = String::new();
    let mut calls = Vec::new();
    let mut pending = BTreeMap::new();
    for event in events {
        match event {
            StreamEvent::Text(text) => content.push_str(&text),
            StreamEvent::Reasoning(text) => reasoning.push_str(&text),
            StreamEvent::Call(call) => calls.push(call),
            StreamEvent::CallStart { index, name } => {
                pending.insert(
                    index,
                    ParsedToolCall {
                        name,
                        arguments: String::new(),
                    },
                );
            }
            StreamEvent::CallArguments { index, arguments } => {
                if let Some(call) = pending.get_mut(&index) {
                    call.arguments.push_str(&arguments);
                }
            }
            StreamEvent::CallEnd { index } => {
                if let Some(call) = pending.remove(&index) {
                    calls.push(call);
                }
            }
        }
    }
    ParsedOutput {
        content,
        reasoning: (!reasoning.is_empty()).then_some(reasoning),
        calls,
        truncated,
    }
}

/// Split reasoning, tool calls and assistant text out of one completed model response.
///
/// This uses the JSON-block dialect; prefer [`parse_with`] with the dialect the package's
/// template asks for.
///
/// # Errors
/// Returns an invalid-input error when a tool-call block carries more than
/// `MAX_TOOL_CALLS` calls or an argument payload above `MAX_TOOL_ARGUMENT_BYTES`.
pub fn parse(text: &str) -> infer_core::Result<ParsedOutput> {
    parse_with(text, ToolDialect::JsonBlock, None)
}

/// Parse a complete response in the dialect the package's template asks the model to emit.
///
/// This is [`OutputStreamParser`] fed the whole response at once, so the streamed and complete
/// forms of one response agree by construction. A call whose name is not in `declared` is left
/// in the content as text: the service does not publish an undeclared call and does not rewrite
/// the model's name into a declared one.
///
/// # Errors
/// Returns an invalid-input error when a tool-call block carries more than
/// `MAX_TOOL_CALLS` calls or an argument payload above `MAX_TOOL_ARGUMENT_BYTES`.
pub fn parse_with(
    text: &str,
    dialect: ToolDialect,
    declared: Option<&BTreeSet<String>>,
) -> infer_core::Result<ParsedOutput> {
    let mut parser = OutputStreamParser::new(dialect, declared.cloned());
    let mut events = parser.feed(text)?;
    events.extend(parser.finish()?);
    Ok(assemble(events, parser.truncated()))
}

/// Largest char boundary at or below `index`.
fn floor_boundary(text: &str, index: usize) -> usize {
    let mut index = index.min(text.len());
    while index > 0 && !text.is_char_boundary(index) {
        index -= 1;
    }
    index
}

/// Longest suffix of `text` that is a proper prefix of `marker`.
fn marker_prefix_len(text: &str, marker: &str) -> usize {
    let bytes = text.as_bytes();
    let marker = marker.as_bytes();
    let max = marker.len().min(bytes.len());
    (1..=max)
        .rev()
        .find(|&len| {
            text.is_char_boundary(text.len() - len) && bytes[text.len() - len..] == marker[..len]
        })
        .unwrap_or(0)
}

/// Bytes that must stay buffered before the next `feed`.
///
/// A marker prefix and any whitespace immediately before it are both held, because that
/// whitespace is a separator that only becomes real text if the marker never completes.
fn hold_len(buffer: &str, marker: &str, whitespace_start: usize) -> usize {
    let prefix = marker_prefix_len(buffer, marker);
    if prefix == 0 {
        return buffer.len() - whitespace_start;
    }
    let mut start = buffer.len() - prefix;
    for (index, ch) in buffer[..start].char_indices().rev() {
        if !ch.is_whitespace() {
            break;
        }
        start = index;
    }
    buffer.len() - start
}
